import assert from 'node:assert/strict';
import { inspect, percentile } from './validate.mjs';
import { synthetic } from './make-synthetic.mjs';
const mutate = f => { const e = synthetic(); f(e); return inspect(e); };
const report = inspect(synthetic());
assert.equal(report.decision, 'review_required'); assert.equal(report.synthetic, true);
assert.deepEqual(report.cohorts[0].variants.map(v => [v.n,v.medianMS,v.p95MS]), [[20,89.5,98],[20,79.5,88]]);
assert.equal(percentile([3,1,2],.95),3); assert.throws(() => percentile([], .95));
assert.throws(() => percentile([NaN], .95));
assert.equal(mutate(e => e.records[0].elapsedMS = null).decision,'invalid_capture');
assert.equal(mutate(e => e.records[0].source = 'native-unannotated').decision,'invalid_capture');
assert.equal(mutate(e => e.records[0].device = 'invented phone').decision,'invalid_capture');
assert.equal(mutate(e => e.records[0].ordinal = e.records[1].ordinal).decision,'invalid_capture');
assert.equal(mutate(e => { e.records[0].outcome = 'incorrect'; e.records[0].correct = false; }).decision,'correctness_failure');
assert.equal(mutate(e => e.records[0].pressureEnd = 'serious').decision,'invalid_capture');
assert.equal(mutate(e => e.records[0].workers = 2).decision,'insufficient_samples');
assert.equal(mutate(e => e.records[0].revision = 'another-revision').decision,'invalid_capture');
assert.equal(mutate(e => { e.records[0].outcome = 'preparation-failure'; e.records[0].elapsedMS = null; e.records[0].correct = null; }).decision,'invalid_capture');
assert.equal(mutate(e => { e.records[0].outcome = 'timeout'; e.records[0].elapsedMS = null; e.records[0].correct = null; }).cohorts[0].variants[0].counts.timeout,1);
assert.equal(mutate(e => { e.records[0].outcome = 'cancelled'; e.records[0].elapsedMS = null; e.records[0].correct = null; }).cohorts[0].variants[0].attempts,20);
assert.equal(mutate(e => e.records[0].elapsedMS = -1).decision,'invalid_capture');
assert.equal(inspect({schema:1,records:[]}).decision,'invalid_capture');
console.log('PASS: raw provenance, cohorts, ordering, percentiles, malformed/missing input, correctness, cancellation and timeout denominators');
